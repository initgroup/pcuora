-- Execute only in your assigned schema. Existing BOOK/CUSTOMER/ORDERS are never touched.
-- The Python initializer ignores ORA-00955 only for these CREATE TABLE statements.
CREATE TABLE OML_BOOK (
  BOOK_ID NUMBER PRIMARY KEY, TITLE VARCHAR2(120) NOT NULL,
  CATEGORY VARCHAR2(30) NOT NULL, PRICE NUMBER(10,0) NOT NULL
);
/
CREATE TABLE OML_CUSTOMER (
  CUSTOMER_ID NUMBER PRIMARY KEY, DISPLAY_NAME VARCHAR2(60) NOT NULL
);
/
CREATE TABLE OML_ORDERS (
  ORDER_ID NUMBER NOT NULL, CUSTOMER_ID NUMBER REFERENCES OML_CUSTOMER(CUSTOMER_ID),
  BOOK_ID NUMBER REFERENCES OML_BOOK(BOOK_ID), ORDER_DATE DATE NOT NULL,
  SALEPRICE NUMBER(10,0) NOT NULL, PRIMARY KEY(ORDER_ID, BOOK_ID)
);
/
CREATE TABLE OML_FEATURES (
  CUSTOMER_ID NUMBER PRIMARY KEY,
  ORDER_COUNT NUMBER NOT NULL CHECK(ORDER_COUNT BETWEEN 1 AND 100),
  TOTAL_AMOUNT NUMBER NOT NULL CHECK(TOTAL_AMOUNT BETWEEN 0 AND 10000000),
  RECENCY_DAYS NUMBER NOT NULL CHECK(RECENCY_DAYS BETWEEN 0 AND 92),
  CATEGORY_COUNT NUMBER NOT NULL CHECK(CATEGORY_COUNT BETWEEN 1 AND 8),
  LABEL VARCHAR2(12) NOT NULL CHECK(LABEL IN ('REBUY','NO_REBUY')),
  SPLIT VARCHAR2(5) NOT NULL CHECK(SPLIT IN ('TRAIN','TEST'))
);
/
CREATE TABLE OML_LAB_STATE (
  ID NUMBER PRIMARY KEY CHECK(ID=1), DATA_REV NUMBER DEFAULT 1 NOT NULL,
  MODEL_REV NUMBER, TRAINED_AT TIMESTAMP, SOURCE_NAME VARCHAR2(120),
  RULE_TRAINED_AT TIMESTAMP
);
/
CREATE OR REPLACE VIEW OML_DERIVED_FEATURES AS
WITH past AS (
  SELECT o.CUSTOMER_ID, COUNT(DISTINCT o.ORDER_ID) ORDER_COUNT,
    SUM(o.SALEPRICE) TOTAL_AMOUNT,
    DATE '2026-10-01'-MAX(o.ORDER_DATE) RECENCY_DAYS,
    COUNT(DISTINCT b.CATEGORY) CATEGORY_COUNT
  FROM OML_ORDERS o JOIN OML_BOOK b ON b.BOOK_ID=o.BOOK_ID
  WHERE o.ORDER_DATE >= DATE '2026-07-01' AND o.ORDER_DATE < DATE '2026-10-01'
  GROUP BY o.CUSTOMER_ID
), labels AS (
  SELECT c.CUSTOMER_ID,
    CASE WHEN COUNT(o.ORDER_ID)>0 THEN 'REBUY' ELSE 'NO_REBUY' END LABEL
  FROM OML_CUSTOMER c LEFT JOIN OML_ORDERS o
    ON o.CUSTOMER_ID=c.CUSTOMER_ID
    AND o.ORDER_DATE >= DATE '2026-10-01' AND o.ORDER_DATE < DATE '2026-11-01'
  GROUP BY c.CUSTOMER_ID
)
SELECT p.*, l.LABEL FROM past p JOIN labels l ON l.CUSTOMER_ID=p.CUSTOMER_ID;
/
-- ID identifies a case; SPLIT and future outcomes are deliberately excluded as predictors.
CREATE OR REPLACE VIEW OML_TRAIN_V AS
SELECT CUSTOMER_ID, ORDER_COUNT, TOTAL_AMOUNT, RECENCY_DAYS, CATEGORY_COUNT, LABEL
FROM OML_FEATURES WHERE SPLIT='TRAIN';
/
CREATE OR REPLACE VIEW OML_BASKET_V AS
SELECT DISTINCT o.ORDER_ID, b.CATEGORY
FROM OML_ORDERS o JOIN OML_BOOK b ON o.BOOK_ID=b.BOOK_ID
WHERE o.ORDER_DATE >= DATE '2026-07-01' AND o.ORDER_DATE < DATE '2026-10-01';
/
