CREATE OR REPLACE PACKAGE OML_LAB AUTHID CURRENT_USER AS
  PROCEDURE REFRESH_SAMPLE;
  PROCEDURE TRAIN_CLASSIFIER;
  PROCEDURE PREDICT_RANK(p_orders NUMBER, p_amount NUMBER, p_recency NUMBER, p_categories NUMBER, p_result OUT SYS_REFCURSOR);
  PROCEDURE EVALUATE_MODEL(p_result OUT SYS_REFCURSOR);
  PROCEDURE MODEL_DETAILS(p_result OUT SYS_REFCURSOR);
  PROCEDURE MODEL_SETTINGS(p_result OUT SYS_REFCURSOR);
  PROCEDURE CORRELATION(p_result OUT SYS_REFCURSOR);
  PROCEDURE TRAIN_RULES;
  PROCEDURE RULES(p_result OUT SYS_REFCURSOR);
END OML_LAB;
/
CREATE OR REPLACE PACKAGE BODY OML_LAB AS
  PROCEDURE drop_owned_model(p_name VARCHAR2) IS n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM USER_MINING_MODELS WHERE MODEL_NAME=p_name;
    IF n>0 THEN DBMS_DATA_MINING.DROP_MODEL(p_name); END IF;
  END;

  PROCEDURE require_model IS n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM OML_LAB_STATE s
    WHERE s.ID=1 AND s.DATA_REV=s.MODEL_REV
      AND EXISTS(SELECT 1 FROM USER_MINING_MODELS WHERE MODEL_NAME='OML_REBUY_DT');
    IF n=0 THEN RAISE_APPLICATION_ERROR(-20002,'Train current data first'); END IF;
  END;

  PROCEDURE REFRESH_SAMPLE IS
  BEGIN
    DELETE FROM OML_FEATURES;
    INSERT INTO OML_FEATURES
    SELECT CUSTOMER_ID, ORDER_COUNT, TOTAL_AMOUNT, RECENCY_DAYS, CATEGORY_COUNT, LABEL,
      CASE WHEN MOD(rn,5)=0 THEN 'TEST' ELSE 'TRAIN' END
    FROM (SELECT d.*, ROW_NUMBER() OVER(PARTITION BY LABEL ORDER BY ORA_HASH(CUSTOMER_ID,4294967295,42),CUSTOMER_ID) rn
          FROM OML_DERIVED_FEATURES d);
    UPDATE OML_LAB_STATE SET DATA_REV=DATA_REV+1, MODEL_REV=NULL, SOURCE_NAME='madang synthetic sample' WHERE ID=1;
    -- Caller commits the complete operation.
  END;

  PROCEDURE TRAIN_CLASSIFIER IS
    cfg DBMS_DATA_MINING.SETTING_LIST; n NUMBER; rev NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM OML_FEATURES;
    IF n<30 OR n>1000 THEN RAISE_APPLICATION_ERROR(-20001,'Use 30..1000 rows'); END IF;
    SELECT COUNT(*) INTO n FROM (
      SELECT SPLIT,LABEL FROM OML_FEATURES GROUP BY SPLIT,LABEL HAVING COUNT(*)>=3
    );
    IF n<>4 THEN RAISE_APPLICATION_ERROR(-20001,'Each split must contain both labels, at least 3 each'); END IF;
    SELECT DATA_REV INTO rev FROM OML_LAB_STATE WHERE ID=1;
    UPDATE OML_LAB_STATE SET MODEL_REV=NULL WHERE ID=1;
    COMMIT; -- CREATE_MODEL is DDL: do not mix uncommitted uploads with training.
    drop_owned_model('OML_REBUY_DT');
    cfg('ALGO_NAME'):='ALGO_DECISION_TREE';
    cfg('PREP_AUTO'):='ON';
    cfg('TREE_IMPURITY_METRIC'):='TREE_IMPURITY_GINI';
    cfg('TREE_TERM_MAX_DEPTH'):='4';
    cfg('TREE_TERM_MINREC_NODE'):='5';
    cfg('TREE_TERM_MINREC_SPLIT'):='10';
    DBMS_DATA_MINING.CREATE_MODEL2(
      model_name=>'OML_REBUY_DT', mining_function=>DBMS_DATA_MINING.CLASSIFICATION,
      data_query=>'SELECT * FROM OML_TRAIN_V', set_list=>cfg,
      case_id_column_name=>'CUSTOMER_ID', target_column_name=>'LABEL');
    UPDATE OML_LAB_STATE SET MODEL_REV=rev,TRAINED_AT=SYSTIMESTAMP WHERE ID=1;
    COMMIT;
  END;

  PROCEDURE PREDICT_RANK(p_orders NUMBER, p_amount NUMBER, p_recency NUMBER, p_categories NUMBER, p_result OUT SYS_REFCURSOR) IS
  BEGIN
    require_model;
    IF p_orders IS NULL OR p_amount IS NULL OR p_recency IS NULL OR p_categories IS NULL
      OR p_orders<1 OR p_orders>100 OR p_orders<>TRUNC(p_orders)
      OR p_amount<0 OR p_amount>10000000 OR p_recency<0 OR p_recency>92
      OR p_recency<>TRUNC(p_recency) OR p_categories<1 OR p_categories>8 OR p_categories<>TRUNC(p_categories)
    THEN RAISE_APPLICATION_ERROR(-20004,'Invalid feature values'); END IF;
    OPEN p_result FOR
      'SELECT ROW_NUMBER() OVER(ORDER BY p.PROBABILITY DESC,p.PREDICTION) RANK,
        p.PREDICTION LABEL,p.PROBABILITY
       FROM TABLE(PREDICTION_SET(OML_REBUY_DT USING
        :a AS ORDER_COUNT,:b AS TOTAL_AMOUNT,:c AS RECENCY_DAYS,:d AS CATEGORY_COUNT)) p
       ORDER BY p.PROBABILITY DESC,p.PREDICTION'
      USING p_orders,p_amount,p_recency,p_categories;
  END;

  PROCEDURE EVALUATE_MODEL(p_result OUT SYS_REFCURSOR) IS
  BEGIN
    require_model;
    OPEN p_result FOR
      'SELECT LABEL ACTUAL,PREDICTION(OML_REBUY_DT USING
       ORDER_COUNT,TOTAL_AMOUNT,RECENCY_DAYS,CATEGORY_COUNT) PREDICTED,COUNT(*) N
       FROM OML_FEATURES WHERE SPLIT=''TEST''
       GROUP BY LABEL,PREDICTION(OML_REBUY_DT USING ORDER_COUNT,TOTAL_AMOUNT,RECENCY_DAYS,CATEGORY_COUNT)
       ORDER BY 1,2';
  END;

  PROCEDURE MODEL_DETAILS(p_result OUT SYS_REFCURSOR) IS
  BEGIN
    require_model;
    OPEN p_result FOR 'SELECT NODE,PARENT,NODE_SUPPORT,PREDICTED_TARGET_VALUE,
      ATTRIBUTE_NAME,OPERATOR,XMLSERIALIZE(CONTENT VALUE AS CLOB) SPLIT_VALUE
      FROM DM$VOOML_REBUY_DT ORDER BY NODE FETCH FIRST 60 ROWS ONLY';
  END;

  PROCEDURE MODEL_SETTINGS(p_result OUT SYS_REFCURSOR) IS
  BEGIN
    require_model;
    OPEN p_result FOR SELECT SETTING_NAME,SETTING_VALUE FROM USER_MINING_MODEL_SETTINGS
      WHERE MODEL_NAME='OML_REBUY_DT' ORDER BY SETTING_NAME;
  END;

  PROCEDURE CORRELATION(p_result OUT SYS_REFCURSOR) IS
  BEGIN
    -- A descriptive SQL statistic, not a DBMS_DATA_MINING model.
    -- TRAIN only: do not use held-out TEST observations to select features.
    OPEN p_result FOR SELECT COUNT(*) N, CORR(ORDER_COUNT,TOTAL_AMOUNT) R,
      MIN(ORDER_COUNT) MIN_ORDERS,MAX(ORDER_COUNT) MAX_ORDERS
      FROM OML_FEATURES WHERE SPLIT='TRAIN';
  END;

  PROCEDURE TRAIN_RULES IS
    cfg DBMS_DATA_MINING.SETTING_LIST; n NUMBER;
  BEGIN
    SELECT COUNT(DISTINCT ORDER_ID) INTO n FROM OML_BASKET_V;
    IF n<10 OR n>2000 THEN RAISE_APPLICATION_ERROR(-20004,'Use 10..2000 small baskets'); END IF;
    UPDATE OML_LAB_STATE SET RULE_TRAINED_AT=NULL WHERE ID=1;
    COMMIT;
    drop_owned_model('OML_BASKET_AR');
    cfg('ALGO_NAME'):='ALGO_APRIORI_ASSOCIATION_RULES';
    cfg('ODMS_ITEM_ID_COLUMN_NAME'):='CATEGORY';
    cfg('ASSO_MIN_SUPPORT'):='0.05';
    cfg('ASSO_MIN_CONFIDENCE'):='0.3';
    cfg('ASSO_MAX_RULE_LENGTH'):='2';
    DBMS_DATA_MINING.CREATE_MODEL2(
      model_name=>'OML_BASKET_AR', mining_function=>DBMS_DATA_MINING.ASSOCIATION,
      data_query=>'SELECT ORDER_ID,CATEGORY FROM OML_BASKET_V',
      set_list=>cfg,case_id_column_name=>'ORDER_ID');
    UPDATE OML_LAB_STATE SET RULE_TRAINED_AT=SYSTIMESTAMP WHERE ID=1;
    COMMIT;
  END;

  PROCEDURE RULES(p_result OUT SYS_REFCURSOR) IS n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM USER_MINING_MODELS WHERE MODEL_NAME='OML_BASKET_AR';
    IF n=0 THEN RAISE_APPLICATION_ERROR(-20003,'Train rules first'); END IF;
    OPEN p_result FOR 'SELECT RULE_ID,ANTECEDENT_PREDICATE ANTECEDENT,
      CONSEQUENT_PREDICATE CONSEQUENT,RULE_SUPPORT,RULE_CONFIDENCE,RULE_LIFT
      FROM DM$VAOML_BASKET_AR
      ORDER BY RULE_LIFT DESC,RULE_CONFIDENCE DESC,RULE_ID FETCH FIRST 20 ROWS ONLY';
  END;
END OML_LAB;
